SELECT
  -- 1. 시계열 및 날짜 차원
  SAFE_CAST(DELIVERY_YMD AS DATE) AS delivery_date,
  EXTRACT(YEAR FROM SAFE_CAST(DELIVERY_YMD AS DATE)) AS year,
  EXTRACT(MONTH FROM SAFE_CAST(DELIVERY_YMD AS DATE)) AS month,
  EXTRACT(DAY FROM SAFE_CAST(DELIVERY_YMD AS DATE)) AS day,
  DATE_TRUNC(SAFE_CAST(DELIVERY_YMD AS DATE), MONTH) AS year_month_date,
  FORMAT_DATE('%Y-%m', SAFE_CAST(DELIVERY_YMD AS DATE)) AS year_month_str,
  FORMAT_DATE('%a', SAFE_CAST(DELIVERY_YMD AS DATE)) AS day_of_week_en,
  EXTRACT(DAYOFWEEK FROM SAFE_CAST(DELIVERY_YMD AS DATE)) AS day_of_week_cd,
  CASE 
    WHEN EXTRACT(DAYOFWEEK FROM SAFE_CAST(DELIVERY_YMD AS DATE)) IN (1, 7) THEN 'Weekend'
    ELSE 'Weekday'
  END AS is_weekend,

  -- 2. 거점 및 OD 노선 차원
  SENDER_SIDO_NM AS sender_sido_nm,
  SENDER_SIDO_CD AS sender_sido_cd,
  RECEIVER_SIDO_NM AS receiver_sido_nm,
  RECEIVER_SIDO_CD AS receiver_sido_cd,
  RECEIVER_SIGUNGU_NM AS receiver_sigungu_nm,
  RECEIVER_SIGUNGU_CD AS receiver_sigungu_cd,
  CONCAT(SENDER_SIDO_NM, ' -> ', RECEIVER_SIGUNGU_NM) AS od_route_name,

  -- 3. 11개 카테고리별 물동량
  COALESCE(CAT_VOL_FURNITURE_INTERIOR, 0) AS vol_furniture_interior,
  COALESCE(CAT_VOL_ETC, 0) AS vol_etc,
  COALESCE(CAT_VOL_BOOKS_MUSIC, 0) AS vol_books_music,
  COALESCE(CAT_VOL_DIGITAL_APPLIANCES, 0) AS vol_digital_appliances,
  COALESCE(CAT_VOL_LIVING_HEALTH, 0) AS vol_living_health,
  COALESCE(CAT_VOL_SPORTS_LEISURE, 0) AS vol_sports_leisure,
  COALESCE(CAT_VOL_FOOD, 0) AS vol_food,
  COALESCE(CAT_VOL_BABY_KIDS, 0) AS vol_baby_kids,
  COALESCE(CAT_VOL_FASHION_CLOTHING, 0) AS vol_fashion_clothing,
  COALESCE(CAT_VOL_FASHION_ACC, 0) AS vol_fashion_acc,
  COALESCE(CAT_VOL_COSMETICS_BEAUTY, 0) AS vol_cosmetics_beauty,

  -- 4. 총 물동량 합산 (total_vol)
  (
    COALESCE(CAT_VOL_FURNITURE_INTERIOR, 0) + COALESCE(CAT_VOL_ETC, 0) +
    COALESCE(CAT_VOL_BOOKS_MUSIC, 0) + COALESCE(CAT_VOL_DIGITAL_APPLIANCES, 0) +
    COALESCE(CAT_VOL_LIVING_HEALTH, 0) + COALESCE(CAT_VOL_SPORTS_LEISURE, 0) +
    COALESCE(CAT_VOL_FOOD, 0) + COALESCE(CAT_VOL_BABY_KIDS, 0) +
    COALESCE(CAT_VOL_FASHION_CLOTHING, 0) + COALESCE(CAT_VOL_FASHION_ACC, 0) +
    COALESCE(CAT_VOL_COSMETICS_BEAUTY, 0)
  ) AS total_vol
FROM
  `OcountryDseoul`